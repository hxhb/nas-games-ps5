#!/usr/bin/env python3
"""Embed the browser UI into a C source file without external dependencies."""

from __future__ import annotations

import pathlib
import sys


CONTENT_TYPES = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".ico": "image/x-icon",
}


def c_identifier(name: str) -> str:
    result = "".join(ch if ch.isalnum() else "_" for ch in name).strip("_")
    return "asset_" + (result or "data")


def c_bytes(data: bytes) -> str:
    if not data:
        return "0"
    rows = []
    for offset in range(0, len(data), 16):
        chunk = data[offset : offset + 16]
        rows.append("    " + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    return "\n".join(rows)


def main() -> int:
    if len(sys.argv) != 4:
        print(f"usage: {sys.argv[0]} UI_DIR HEADER OUT_C", file=sys.stderr)
        return 2

    ui_dir = pathlib.Path(sys.argv[1])
    header_path = pathlib.Path(sys.argv[2])
    source_path = pathlib.Path(sys.argv[3])
    files = sorted(path for path in ui_dir.iterdir() if path.is_file())
    if not files:
        print(f"no UI files in {ui_dir}", file=sys.stderr)
        return 1

    assets = []
    for path in files:
        route = "/" + path.name
        content_type = CONTENT_TYPES.get(path.suffix.lower(), "application/octet-stream")
        assets.append((path, route, content_type, path.read_bytes()))

    header = [
        "#ifndef NASGAMES_UI_ASSETS_H",
        "#define NASGAMES_UI_ASSETS_H",
        "",
        "#include <stddef.h>",
        "",
        "typedef struct {",
        "    const char *name;",
        "    const char *content_type;",
        "    const char *data;",
        "    size_t size;",
        "} NgUiAsset;",
        "",
        "extern const NgUiAsset ng_ui_assets[];",
        "extern const size_t ng_ui_asset_count;",
        "",
        "#endif",
        "",
    ]
    header_path.write_text("\n".join(header), encoding="utf-8")

    source = [
        '#include "ui_assets.h"',
        "",
        "/* Generated by tools/embed_assets.py. Do not edit directly. */",
        "",
    ]
    for index, (_, route, _, data) in enumerate(assets):
        source.extend(
            [
                f"static const unsigned char {c_identifier(route)}_{index}[] = {{",
                c_bytes(data),
                "};",
                "",
            ]
        )
    source.append("const NgUiAsset ng_ui_assets[] = {")
    for index, (_, route, content_type, data) in enumerate(assets):
        source.extend(
            [
                "    {",
                f'        .name = "{route}",',
                f'        .content_type = "{content_type}",',
                f"        .data = (const char *){c_identifier(route)}_{index},",
                f"        .size = {len(data)},",
                "    },",
            ]
        )
    source.extend(
        [
            "};",
            "const size_t ng_ui_asset_count = sizeof(ng_ui_assets) / sizeof(ng_ui_assets[0]);",
            "",
        ]
    )
    source_path.write_text("\n".join(source), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
